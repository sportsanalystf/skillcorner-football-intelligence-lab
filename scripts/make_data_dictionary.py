def col_table(df: pd.DataFrame, max_rows: int | None = None, sample_col: bool = True) -> str:
    rows = []
    for c in df.columns:
        s = df[c]
        nn = s.notna()
        ex = ""
        if sample_col and nn.any():
            vals = s[nn].head(200).unique()[:3]
            ex = ", ".join(f"`{v}`" for v in [_fmt(v) for v in vals])
        rows.append(
            {
                "column": f"`{c}`",
                "dtype": str(s.dtype),
                "non-null": f"{nn.mean():.0%}",
                "example values": ex,
            }
        )
    t = pd.DataFrame(rows)
    if max_rows:
        t = t.head(max_rows)
    return t.to_markdown(index=False)


def _fmt(v):
    if isinstance(v, float):
        return round(v, 3)
    s = str(v)
    return s if len(s) <= 28 else s[:26] + "..."


