def _family_matrix(ev: pd.DataFrame) -> str:
    families = {
        "position (`x_start`, `y_start`, ...)": ["x_start", "y_start"],
        "EPV (`possession_epv_*`, `pass_epv_*`)": ["possession_epv_total"],
        "pressure (`overall_pressure_*`, ...)": ["overall_pressure_start"],
        "pass outcome (`pass_outcome`, `xpass_completion`)": ["pass_outcome", "xpass_completion"],
        "line breaks (`first_line_break`, ...)": ["first_line_break"],
        "run subtype (`event_subtype`)": ["event_subtype"],
        "pressing chain (`pressing_chain*`)": ["pressing_chain"],
        "targeted player (`player_targeted_*`)": ["player_targeted_id"],
        "defensive line (`last_defensive_line_x_*`)": ["last_defensive_line_x_start"],
    }
    order = ["player_possession", "passing_option", "off_ball_run", "on_ball_engagement"]
    lines = []
    for label, cols in families.items():
        cells = []
        for et in order:
            sub = ev[ev.event_type == et]
            fracs = [sub[c].notna().mean() for c in cols if c in ev.columns]
            f = float(np.mean(fracs)) if fracs else 0.0
            cells.append("--" if f < 0.01 else f"{f:.0%}")
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _band_table(ev: pd.DataFrame) -> str:
    rows = []
    for c in [
        "overall_pressure_start", "overall_pressure_end", "reception_difficulty_start",
        "space_constraint_start", "time_to_impact_start", "time_to_impact_end",
        "passing_option_ease_start", "passing_option_ease_end",
    ]:
        if c not in ev.columns:
            continue
        pairs = (
            ev[[c, c + "_id"]].dropna().drop_duplicates().sort_values(c + "_id")
        )
        bands = " < ".join(f"{int(i)}=`{v}`" for v, i in pairs.itertuples(index=False))
        rows.append({"column": f"`{c}`", "non-null": f"{ev[c].notna().mean():.0%}", "bands": bands})
    return pd.DataFrame(rows).to_markdown(index=False)


